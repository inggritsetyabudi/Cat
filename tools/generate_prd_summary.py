#!/usr/bin/env python3
"""Generate the compact PRD from authored Ringkas: lines (Python stdlib only)."""
from __future__ import annotations

import argparse
import re
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
SOURCE = ROOT / "cat-northstar/PRD.md"
OUTPUT = ROOT / "cat-northstar/PRD-RINGKAS.md"
FENCE_OPEN = re.compile(r"^ {0,3}(`{3,}|~{3,})(.*)$")
FENCE_CLOSE = re.compile(r"^ {0,3}(`+|~+)[ \t]*$")
HEADING = re.compile(r"^ {0,3}(#{1,6})(?:[ \t]+(.*)|[ \t]*)$")
MARKER_LIKE = re.compile(r"^\s*(?:[-*]\s+|\*\*)?Ringkas\b", re.IGNORECASE)
MARKER = re.compile(r"Ringkas: (\S(?:.*\S)?)")
HEADER = (
    "# C@ — Ringkasan PRD\n\n"
    "<!-- Generated by tools/generate_prd_summary.py; do not edit. -->\n"
    "Sumber: [PRD.md](./PRD.md), hanya heading bagian dan baris `Ringkas:`. "
    "Keputusan lengkap, status implementasi, dan batas versi tetap mengikuti sumber.\n\n"
)


def generate(source: bytes) -> bytes:
    """Validate every level-two section and copy only its heading and marker text."""
    text = source.decode("utf-8", errors="strict")
    if text.startswith("\ufeff"):
        raise ValueError("PRD must be UTF-8 without a BOM")
    if "\r" in text.replace("\r\n", ""):
        raise ValueError("PRD has a bare CR; use LF or CRLF line endings")
    lines = text.replace("\r\n", "\n").split("\n")
    sections: list[tuple[str, str]] = []
    heading: str | None = None
    opening_line = 0
    summary: str | None = None
    first_content = False
    nested = False
    fence: str | None = None

    def finish() -> None:
        if heading is not None:
            if summary is None:
                raise ValueError(f"line {opening_line}: missing Ringkas: marker for {heading}")
            sections.append((heading, summary))

    for number, line in enumerate(lines, 1):
        if fence is not None:
            close = FENCE_CLOSE.fullmatch(line)
            if close and close[1][0] == fence[0] and len(close[1]) >= len(fence):
                fence = None
            continue
        match = HEADING.fullmatch(line)
        if match and len(match[1]) == 2:
            finish()
            if not (match[2] or "").strip().strip("#").strip():
                raise ValueError(f"line {number}: empty section heading")
            heading, opening_line, summary = line, number, None
            first_content, nested = False, False
            continue
        if match:
            nested = True
        if MARKER_LIKE.match(line):
            marker = MARKER.fullmatch(line)
            if marker is None:
                raise ValueError(f"line {number}: malformed marker; expected Ringkas: <nonempty text> without indentation or trailing whitespace")
            if heading is None:
                raise ValueError(f"line {number}: Ringkas: outside a level-two section")
            if summary is not None:
                raise ValueError(f"line {number}: duplicate Ringkas: marker for {heading}")
            if first_content or nested:
                raise ValueError(f"line {number}: Ringkas: must be the first nonblank line after its level-two heading")
            summary = marker[1]
        if line.strip():
            first_content = True
        match = FENCE_OPEN.fullmatch(line)
        if match:
            fence = match[1]
    if fence is not None:
        raise ValueError("unclosed fenced block")
    finish()
    if not sections:
        raise ValueError("no level-two sections found")
    body = "\n\n".join(f"{title}\n\n{summary}" for title, summary in sections)
    return (HEADER + body + "\n").encode("utf-8")


def main(argv: list[str] | None = None) -> int:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--check", action="store_true", help="fail if the committed output is absent or not byte-identical; never write")
    parser.add_argument("--source", type=Path, default=SOURCE)
    parser.add_argument("--output", type=Path, default=OUTPUT)
    args = parser.parse_args(argv)
    try:
        if args.source.resolve() == args.output.resolve():
            raise ValueError("source and output must be different files")
        expected = generate(args.source.read_bytes())
        if args.check:
            if not args.output.is_file() or args.output.read_bytes() != expected:
                print("PRD summary is missing or stale; run python3 tools/generate_prd_summary.py", file=sys.stderr)
                return 1
            print("PRD summary is in sync (UTF-8, exact bytes)")
        else:
            # Binary I/O avoids platform newline translation and never rewrites the source.
            args.output.write_bytes(expected)
            print(f"Generated {args.output.name}")
    except (OSError, ValueError) as error:
        print(f"PRD summary failed: {error}", file=sys.stderr)
        return 1
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
